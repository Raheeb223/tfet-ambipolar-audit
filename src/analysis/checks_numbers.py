"""In-text numbers for the robustness checks: charged traps, BTBT-parameter UQ, calibration
field coverage, U-shaped D_it. Writes paper/generated/numbers_checks.tex.
Run after: audit.charged_traps, uq.btbt_uq, analysis.coverage, run_audit (calibrated).
"""

import os

import numpy as np
import pandas as pd

from src.analysis.figures import GEN, SHORT, _e

AUD = os.path.join("results", "audit_cal")


def main():
    N = {}
    ch = pd.read_csv(os.path.join(AUD, "charged_traps_S.csv")).dropna()
    N["ChargedMaxdS"] = f"{ch.dS.abs().max():.2f}"
    N["ChargedMaxdSNotLDD"] = f"{ch[ch.device != 'low_drain_doping'].dS.abs().max():.2f}"
    N["ChargedMaxdSOneE"] = f"{ch[ch.D_it <= 1e12].dS.abs().max():.2f}"
    raw = pd.read_csv(os.path.join(AUD, "charged_traps.csv"))
    r = raw[(raw.device == "reference") & (raw.D_it == 5e12)].pivot_table(
        index=["T_K", "Vg"], columns="charged", values="I_btbt_nl")
    N["ChargedBtbtDropMax"] = f"{np.log10(r[False] / r[True]).max():.2f}"

    for Vg, tag in ((-1.0, ""), (-0.6, "Six"), (-0.2, "Two")):
        u = pd.read_csv(os.path.join("results", "uq", f"uq_summary_Vg{Vg:+.1f}.csv"))
        nl = u[(u.model == "nonlocal") & np.isclose(u.T_K, 300.0)]
        hw = ((nl["S_1e+12_p95"] - nl["S_1e+12_p05"]) / 2)
        N[f"UqHalfWidthMax{tag}"] = f"{hw.max():.2f}"
        N[f"UqRankMin{tag}"] = f"{100 * u[['P_rank_0e+00', 'P_rank_1e+12']].min().min():.1f}"
        N[f"UqRankZero{tag}"] = f"{100 * u[u.model == 'nonlocal']['P_rank_0e+00'].min():.1f}"
        for _, row in nl.iterrows():
            k = SHORT[row.device]
            N[f"UqDx{k}{tag}"] = _e(row.Dx_med)
            N[f"UqDxLo{k}{tag}"] = _e(row.Dx_p05)
            N[f"UqDxHi{k}{tag}"] = _e(row.Dx_p95)
        hot = u[(u.model == "nonlocal") & np.isclose(u.T_K, 398.15)]
        for _, row in hot.iterrows():
            N[f"UqDxHot{SHORT[row.device]}{tag}"] = _e(row.Dx_med)

    cov_all = pd.read_csv(os.path.join(AUD, "calibration_coverage.csv"))
    near = cov_all[np.isclose(cov_all.Vg, -0.2) & (cov_all.model == "nonlocal") & (cov_all.device != "reference")]
    N["CovNearFMin"] = f"{near.F_median_MVcm.min():.2f}"
    N["CovNearFMax"] = f"{near.F_median_MVcm.max():.2f}"
    cov = cov_all[cov_all.Vg.isin([-1.0, -0.6])]
    tech = cov[(cov.model == "nonlocal") & cov.device.isin(["heterogate", "low_drain_doping", "gd_underlap"])]
    N["CovTechMin"] = f"{100 * tech.frac_in_range.min():.0f}"
    N["CovFtechMin"] = f"{tech.F_median_MVcm.min():.1f}"
    N["CovFtechMax"] = f"{tech.F_median_MVcm.max():.1f}"
    ext = cov[(cov.model == "nonlocal") & cov.device.isin(["reference", "dual_wf_gate"])]
    N["CovFextMin"] = f"{ext.F_median_MVcm.min():.1f}"
    N["CovFextMax"] = f"{ext.F_median_MVcm.max():.1f}"
    loc = cov[cov.model == "local"]
    N["CovLocFMin"] = f"{loc.F_median_MVcm.min():.1f}"
    N["CovLocFMax"] = f"{loc.F_median_MVcm.max():.1f}"
    N["CovLocInMax"] = f"{100 * loc.frac_in_range.max():.0f}"

    tab = os.path.join(AUD, "table.csv")
    if os.path.exists(tab):
        df = pd.read_csv(tab)
        d = df[(df.kind == "realistic") & (df.btbt_model == "nonlocal") & np.isclose(df.tau, 1e-7)
               & np.isclose(df.Vg, -1.0) & np.isclose(df.T_K, 300.0) & np.isclose(df.D_it, 1e12)]
        p = d.pivot_table(index="device", columns="dit_profile", values="I_it")
        N["UshapeItRatioMin"] = f"{(p.u_shape / p.uniform).min():.1f}"
        N["UshapeItRatioMax"] = f"{(p.u_shape / p.uniform).max():.1f}"
        ref = p.loc["reference"]
        sinf = {k: np.log10(ref[k] / p[k]) for k in ("uniform", "u_shape")}
        N["UshapeSinfMaxDiff"] = f"{max(abs(sinf['u_shape'][t] - sinf['uniform'][t]) for t in SHORT):.2f}"
    with open(os.path.join(GEN, "numbers_checks.tex"), "w") as f:
        f.write("% generated by src/analysis/checks_numbers.py -- do not edit\n")
        for k, v in N.items():
            f.write(f"\\newcommand{{\\n{k}}}{{{v}}}\n")
    return N


if __name__ == "__main__":
    for k, v in main().items():
        print(k, v)
